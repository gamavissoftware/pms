-- Map of PMS sales customers (customer_detail.id) to their SAP BP code, from the SAP BP master sheet.
-- The SAP quotation push uses this code as CardCode. Run once per database; later additions are INSERT ... ON DUPLICATE KEY.
CREATE TABLE IF NOT EXISTS SAP_bp_map (
  customer_id INT NOT NULL,
  bp_code VARCHAR(30) NOT NULL,
  matched_by VARCHAR(20) NULL,
  created_at DATETIME NOT NULL,
  PRIMARY KEY (customer_id),
  KEY idx_bp_code (bp_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

